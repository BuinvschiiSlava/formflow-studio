import { slugifyKey } from '../../domain/form-document/form-document.factory';
import {
  FieldCondition,
  FieldOption,
  FieldValidation,
  FormDocument,
  FormFieldNode,
  isDisplayField,
} from '../../domain/form-document/form-document.model';

export interface TextExport {
  filename: string;
  mediaType: 'application/json' | 'text/typescript';
  content: string;
}

function orderedValidation(validation: FieldValidation): Record<string, unknown> {
  return {
    ...(validation.required !== undefined ? { required: validation.required } : {}),
    ...(validation.minLength !== undefined ? { minLength: validation.minLength } : {}),
    ...(validation.maxLength !== undefined ? { maxLength: validation.maxLength } : {}),
    ...(validation.min !== undefined ? { min: validation.min } : {}),
    ...(validation.max !== undefined ? { max: validation.max } : {}),
    ...(validation.pattern !== undefined ? { pattern: validation.pattern } : {}),
  };
}

function orderedCondition(condition: FieldCondition): Record<string, unknown> {
  return {
    action: condition.action,
    sourceFieldId: condition.sourceFieldId,
    operator: condition.operator,
    ...(condition.value !== undefined ? { value: condition.value } : {}),
  };
}

function orderedOption(option: FieldOption): Record<string, unknown> {
  return { id: option.id, label: option.label, value: option.value };
}

function orderedField(field: FormFieldNode): Record<string, unknown> {
  return {
    id: field.id,
    key: field.key,
    type: field.type,
    label: field.label,
    description: field.description,
    placeholder: field.placeholder,
    ...(field.defaultValue !== undefined ? { defaultValue: field.defaultValue } : {}),
    width: field.width,
    options: field.options.map(orderedOption),
    validation: orderedValidation(field.validation),
    ...(field.condition ? { condition: orderedCondition(field.condition) } : {}),
  };
}

function orderedDocument(document: FormDocument): Record<string, unknown> {
  return {
    schemaVersion: document.schemaVersion,
    id: document.id,
    title: document.title,
    description: document.description,
    locale: document.locale,
    submitLabel: document.submitLabel,
    fields: document.fields.map(orderedField),
    createdAt: document.createdAt,
    updatedAt: document.updatedAt,
  };
}

/** Stable property ordering and no timestamps make exports reproducible. */
export function serializeFormDocument(document: FormDocument): string {
  return `${JSON.stringify(orderedDocument(document), null, 2)}\n`;
}

function kebabFilename(value: string): string {
  return slugifyKey(value)
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/_+/g, '-')
    .toLowerCase();
}

export function createJsonExport(document: FormDocument): TextExport {
  return {
    filename: `${kebabFilename(document.title) || 'form'}-formflow.json`,
    mediaType: 'application/json',
    content: serializeFormDocument(document),
  };
}

function escapeComment(value: string): string {
  return value.replace(/\*\//g, '*\\/').replace(/\s+/g, ' ').trim();
}

function propertyName(key: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function stringLiteralUnion(options: readonly FieldOption[]): string {
  const uniqueValues = [...new Set(options.map((option) => option.value))];
  return uniqueValues.length > 0
    ? uniqueValues.map((value) => JSON.stringify(value)).join(' | ')
    : 'string';
}

function fieldType(field: FormFieldNode): string {
  switch (field.type) {
    case 'number':
      return 'number';
    case 'checkbox':
    case 'toggle':
      return 'boolean';
    case 'select':
    case 'radio':
      return stringLiteralUnion(field.options);
    case 'text':
    case 'email':
    case 'textarea':
    case 'date':
      return 'string';
    case 'heading':
    case 'divider':
    case 'section':
      return 'never';
  }
}

function toInterfaceName(title: string): string {
  const slug = slugifyKey(title);
  const pascal = slug
    .replace(/^[a-z]/, (character) => character.toUpperCase())
    .replace(/[^A-Za-z0-9_$]/g, '');
  const safe = /^[A-Za-z_$]/.test(pascal) ? pascal : `Form${pascal}`;
  return `${safe || 'FormFlow'}FormValue`;
}

export function generateTypeScriptModel(
  document: FormDocument,
  interfaceName = toInterfaceName(document.title),
): string {
  const safeInterfaceName = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(interfaceName)
    ? interfaceName
    : 'FormFlowFormValue';
  const fields = document.fields.filter((field) => !isDisplayField(field));
  const lines = [
    '/**',
    ' * Generated by FormFlow Studio.',
    ` * Source form: ${escapeComment(document.title)}`,
    ' */',
    `export interface ${safeInterfaceName} {`,
  ];

  for (const field of fields) {
    const description = escapeComment(field.description || field.label);
    lines.push(`  /** ${description} */`);
    const optional = field.validation.required === true ? '' : '?';
    lines.push(`  ${propertyName(field.key)}${optional}: ${fieldType(field)};`);
  }

  lines.push('}', '');
  return lines.join('\n');
}

export function createTypeScriptExport(document: FormDocument): TextExport {
  return {
    filename: `${kebabFilename(document.title) || 'form'}-model.ts`,
    mediaType: 'text/typescript',
    content: generateTypeScriptModel(document),
  };
}
